def is_managed_bench(bench_config=None) -> bool:
	"""Whether this bench's state is owned by Frappe Cloud."""
	if os.environ.get(MANAGED_ENV_VAR):
		return True

	if bench_config is None:
		from bench.config.common_site_config import get_config

		bench_config = get_config(".")

	return bool(bench_config.get(MANAGED_CONFIG_KEY))


def get_guard_reason(command: str):
	"""Return what goes out of sync if `command` is run on a managed bench."""
	return GUARDED_COMMANDS.get(command)


def confirm_if_managed(command: str, bench_config=None) -> None:
	"""Ask before running a command that desyncs a Frappe Cloud bench.

	Aborts with a non-zero exit code unless the user accepts. No-ops for
	unguarded commands, for benches Frappe Cloud does not manage, when
	BENCH_SKIP_PROD_GUARD is set, and when stdin is not a TTY -- the agent
	runs bench over `docker exec` without one.
	"""
	if not command or os.environ.get(SKIP_ENV_VAR):
		return

	# `bench update --help` shouldn't prompt for a command it never runs
	if {"--help", "-h"}.intersection(sys.argv):
		return

	reason = get_guard_reason(command)
	if not reason:
		return

	if not is_managed_bench(bench_config):
		return

	if not sys.stdin.isatty():
		return

	invocation = " ".join(sys.argv[1:])

	click.secho("\nThis bench is managed by Frappe Cloud.", fg="yellow", bold=True)
	click.secho(f"\n  $ bench {invocation}\n", fg="yellow")
	click.echo(f"{reason}\n")
	click.echo("Use the Frappe Cloud dashboard instead.\n")

	try:
		proceed = click.confirm("Run it anyway?", default=False)
	except click.Abort:
		proceed = False

	if not proceed:
		click.secho(
			f"Aborted. Set {SKIP_ENV_VAR}=1 to bypass this prompt.", fg="red", err=True
		)
		sys.exit(1)

"""Warn before commands that desync a managed bench from its control plane.

On Frappe Cloud the bench in the container is a *replica*, not the source of
truth -- Press owns the Bench and Site records and rebuilds the container from
an image on every deploy. A command run by hand inside the container can push
the two out of sync: an app installed here is missing from the dashboard, a
site dropped here is still billed, config written here is overwritten on the
next config push.

The guard is advisory. It asks before running, defaults to aborting, and gets
out of the way for anything non-interactive (the agent drives benches over
`docker exec` without a TTY) so automation is unaffected.
"""

